/**
 * Tarjima matnini qaytaradi. Til topilmasa yoki kalit yo'q bo'lsa,
 * o'zbek tilidagi (asosiy) matn qaytariladi.
 * @param {string} lang - til kodi (uz, ru, en, ...)
 * @param {string} key - tarjima kaliti
 * @param {Object} vars - {key: value} ko'rinishidagi o'zgaruvchilar ({name} kabi)
 * @returns {string}
 */
function t(lang, key, vars = {}) {
  const dict = translations[lang] || translations[DEFAULT_LANG];
  let text = dict[key];

  if (text === undefined) {
    text = translations[DEFAULT_LANG][key];
  }
  if (text === undefined) {
    return key;
  }

  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

/**
 * Til kodi to'g'ri ekanligini tekshiradi.
 * @param {string} code
 * @returns {boolean}
 */
function isValidLanguage(code) {
  return LANGUAGES.some((l) => l.code === code);
}

/**
 * ctx'dan foydalanuvchi tilini oladi.
 * Foydalanuvchi hujjati kuzatuv middleware tomonidan ctx.state.userDoc'ga yoziladi.
 * @param {Object} ctx - Telegraf konteksti
 * @returns {string} - til kodi
 */
function lang(ctx) {
  const userDoc = ctx && ctx.state && ctx.state.userDoc;
  const code = userDoc && userDoc.language;
  return code && isValidLanguage(code) ? code : DEFAULT_LANG;
}

module.exports = { LANGUAGES, DEFAULT_LANG, t, isValidLanguage, lang, translations };
